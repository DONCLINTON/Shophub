-- ShopHub Marketplace Upgrade — additive migration
-- Run this entire script in Supabase SQL Editor BEFORE deploying the upgraded frontend.
-- This migration does not drop or rewrite existing listings, jobs, applications or reports.

begin;

-- Extend the existing marketplace listings table without changing existing records.
alter table public.listings
  add column if not exists seller_name text,
  add column if not exists subcategory text;

create index if not exists listings_category_subcategory_idx
  on public.listings (category, subcategory);

-- Buyer requests: people publish what they need and their available budget.
create table if not exists public.buyer_requests (
  id bigint generated by default as identity primary key,
  item_name text not null check (char_length(trim(item_name)) between 2 and 160),
  budget_ugx numeric(14,0) not null check (budget_ugx > 0),
  location text not null check (char_length(trim(location)) between 2 and 120),
  requester_name text not null check (char_length(trim(requester_name)) between 2 and 100),
  requester_phone text not null check (char_length(trim(requester_phone)) between 7 and 25),
  details text,
  status text not null default 'open' check (status in ('open','fulfilled','closed')),
  created_at timestamptz not null default now()
);

create index if not exists buyer_requests_status_created_idx
  on public.buyer_requests (status, created_at desc);

alter table public.buyer_requests enable row level security;
drop policy if exists "Public can view open buyer requests" on public.buyer_requests;
create policy "Public can view open buyer requests"
  on public.buyer_requests for select to anon, authenticated
  using (status = 'open');
drop policy if exists "Public can create buyer requests" on public.buyer_requests;
create policy "Public can create buyer requests"
  on public.buyer_requests for insert to anon, authenticated
  with check (
    status = 'open'
    and char_length(trim(item_name)) between 2 and 160
    and budget_ugx > 0
    and char_length(trim(location)) between 2 and 120
    and char_length(trim(requester_name)) between 2 and 100
    and char_length(trim(requester_phone)) between 7 and 25
  );

-- Rental / brokerage listings. Photos are optional; the required fields are
-- property_type, monthly_rent_ugx, location, landlord_type, contact_name, contact_phone.
create table if not exists public.property_listings (
  id bigint generated by default as identity primary key,
  property_type text not null check (property_type in (
    'Single room','Double room','Single self-contained',
    'Double self-contained','Full house','Apartment'
  )),
  monthly_rent_ugx numeric(14,0) not null check (monthly_rent_ugx > 0),
  location text not null check (char_length(trim(location)) between 2 and 120),
  landlord_type text not null default 'landlord' check (landlord_type in ('landlord','broker')),
  contact_name text not null check (char_length(trim(contact_name)) between 2 and 100),
  contact_phone text not null check (char_length(trim(contact_phone)) between 7 and 25),
  landmark text,
  description text,
  image_urls text[] not null default '{}'::text[],
  status text not null default 'published' check (status in ('published','rented','hidden')),
  created_at timestamptz not null default now()
);

create index if not exists property_listings_status_created_idx
  on public.property_listings (status, created_at desc);
create index if not exists property_listings_location_idx
  on public.property_listings (location);
create index if not exists property_listings_type_idx
  on public.property_listings (property_type);

alter table public.property_listings enable row level security;
drop policy if exists "Public can view published properties" on public.property_listings;
create policy "Public can view published properties"
  on public.property_listings for select to anon, authenticated
  using (status = 'published');
drop policy if exists "Public can publish property listings" on public.property_listings;
create policy "Public can publish property listings"
  on public.property_listings for insert to anon, authenticated
  with check (
    status = 'published'
    and monthly_rent_ugx > 0
    and landlord_type in ('landlord','broker')
    and char_length(trim(location)) between 2 and 120
    and char_length(trim(contact_name)) between 2 and 100
    and char_length(trim(contact_phone)) between 7 and 25
  );

-- Active brokerage page: house_rentals (the older property_listings table above
-- is retained for backward compatibility and is not used by brokerage.html).
create table if not exists public.house_rentals (
  id bigint generated by default as identity primary key,
  house_type text not null check (house_type in (
    'Single room','Double room','Full house','Apartment',
    'Single self-contained','Double self-contained'
  )),
  neighbourhood text not null check (char_length(trim(neighbourhood)) between 2 and 100),
  monthly_rent numeric(14,0) not null check (monthly_rent > 0),
  advertiser_type text not null check (advertiser_type in ('Landlord / Owner','Broker / Agent')),
  contact_name text not null check (char_length(trim(contact_name)) between 2 and 90),
  phone text not null check (char_length(trim(phone)) between 7 and 25),
  description text,
  landmarks text,
  image_urls text[] not null default '{}'::text[],
  status text not null default 'active' check (status in ('active','rented','hidden')),
  created_at timestamptz not null default now()
);

-- If an earlier draft already created house_rentals with only part of this
-- shape, add any missing columns without deleting or rewriting existing rows.
alter table public.house_rentals
  add column if not exists house_type text,
  add column if not exists neighbourhood text,
  add column if not exists monthly_rent numeric(14,0),
  add column if not exists advertiser_type text,
  add column if not exists contact_name text,
  add column if not exists phone text,
  add column if not exists description text,
  add column if not exists landmarks text,
  add column if not exists image_urls text[] not null default '{}'::text[],
  add column if not exists status text not null default 'active',
  add column if not exists created_at timestamptz not null default now();

create index if not exists house_rentals_status_created_idx
  on public.house_rentals (status, created_at desc);
create index if not exists house_rentals_neighbourhood_idx
  on public.house_rentals (neighbourhood);
create index if not exists house_rentals_type_idx
  on public.house_rentals (house_type);

alter table public.house_rentals enable row level security;
drop policy if exists "Public can view active house rentals" on public.house_rentals;
create policy "Public can view active house rentals"
  on public.house_rentals for select to anon, authenticated
  using (status = 'active');
drop policy if exists "Public can publish house rentals" on public.house_rentals;
create policy "Public can publish house rentals"
  on public.house_rentals for insert to anon, authenticated
  with check (
    status = 'active'
    and monthly_rent > 0
    and advertiser_type in ('Landlord / Owner','Broker / Agent')
    and char_length(trim(neighbourhood)) between 2 and 100
    and char_length(trim(contact_name)) between 2 and 90
    and char_length(trim(phone)) between 7 and 25
  );

-- Public image bucket for rental photos. Existing item-photos bucket is untouched.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('rental-photos', 'rental-photos', true, 5242880,
        array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view rental photos" on storage.objects;
create policy "Public can view rental photos"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'rental-photos');
drop policy if exists "Public can upload rental photos" on storage.objects;
create policy "Public can upload rental photos"
  on storage.objects for insert to anon, authenticated
  with check (
    bucket_id = 'rental-photos'
  );

commit;

-- Notes:
-- 1. No public UPDATE or DELETE policy is created for buyer requests or property listings.
-- 2. Contact information is visible to site visitors because the purpose is direct contact.
-- 3. The public upload policy permits unauthenticated uploads to rental-photos.
--    Supabase Storage file-size and MIME restrictions are configured above.
-- 4. ShopHub's existing listings, jobs and item-photos storage are not recreated or deleted.
